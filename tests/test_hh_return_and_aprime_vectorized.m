function test_hh_return_and_aprime_vectorized()
%TEST_HH_RETURN_AND_APRIME_VECTORIZED Verify scalar, CPU broadcast, and GPU parity
%   for HumanCapital_Lifecycle_aprimeFn, ReturnFn_SpatialHH, and ReturnFn_SpatialHH_Compact4D.

isOctave = (exist('OCTAVE_VERSION', 'builtin') ~= 0);
hasGpu   = (~isOctave && exist('gpuDeviceCount', 'file') ~= 0 && gpuDeviceCount > 0);

% Shared calibrated lifecycle constants (dt = 5yr step conventions)
dt = 5.0; Jr = 10;
j_s1_start = 2; j_s1_end = 3;
j_s2_start = 4; j_s2_end = 5;
n_s1 = 2;       n_s2 = 2;

phi1_ces = -0.25; gamma1_self = 0.45; gamma1_inv = 0.35; gamma1_par = 0.20; G_ece1 = 0.055;
phi2_ces = -0.50; gamma2_self = 0.55; gamma2_inv = 0.28; gamma2_par = 0.17; G_ece2 = 0.070;
gbar_ece = 0.040; h_par_mean = 1.00;
Q_reg = 1.35; Q_reg_base = 1.35; K_whanau = 0.12;

% -------------------------------------------------------------------------
% PART A: HumanCapital_Lifecycle_aprimeFn across Stage 1, Stage 2, Non-Parent
% -------------------------------------------------------------------------
ic_col     = [0.0; 0.0203; 0.060; 0.140];        % [4 x 1] Node 1 corner, Node 2 AHC, interior
thetac_row = [0.55, 0.85, 1.00, 1.25, 1.55];     % [1 x 5]
[IC_2D, TH_2D] = ndgrid(ic_col, thetac_row);

for agej = [1, 2, 4, 10]
    th_vec = HumanCapital_Lifecycle_aprimeFn(ic_col, thetac_row, agej, ...
        phi1_ces, gamma1_self, gamma1_inv, gamma1_par, G_ece1, ...
        phi2_ces, gamma2_self, gamma2_inv, gamma2_par, G_ece2, ...
        gbar_ece, h_par_mean, ...
        j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_s1, n_s2, ...
        Q_reg, Q_reg_base, K_whanau, Jr, dt);

    check(isequal(size(th_vec), [4, 5]), ...
        sprintf('aprimeFn size mismatch at agej=%d', agej));
    check(all(isfinite(th_vec(:)) & (th_vec(:) > 0)), ...
        sprintf('aprimeFn returned non-positive or non-finite skill at agej=%d', agej));

    th_sca = arrayfun(@(ic, th) HumanCapital_Lifecycle_aprimeFn(ic, th, agej, ...
        phi1_ces, gamma1_self, gamma1_inv, gamma1_par, G_ece1, ...
        phi2_ces, gamma2_self, gamma2_inv, gamma2_par, G_ece2, ...
        gbar_ece, h_par_mean, ...
        j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_s1, n_s2, ...
        Q_reg, Q_reg_base, K_whanau, Jr, dt), IC_2D, TH_2D);

    check(max(abs(th_vec(:) - th_sca(:))) < 1e-12, ...
        sprintf('aprimeFn scalar vs vectorized CPU mismatch at agej=%d', agej));

    if agej == j_s1_start || agej == j_s2_start
        % Higher parental investment must strictly or weakly raise child skill
        check(all(diff(th_vec, 1, 1) >= -1e-12, 'all'), ...
            sprintf('aprimeFn non-monotonic in i_c at parenting agej=%d', agej));
    end

    if hasGpu
        th_gpu = gather(arrayfun(@HumanCapital_Lifecycle_aprimeFn, ...
            gpuArray(IC_2D), gpuArray(TH_2D), agej, ...
            phi1_ces, gamma1_self, gamma1_inv, gamma1_par, G_ece1, ...
            phi2_ces, gamma2_self, gamma2_inv, gamma2_par, G_ece2, ...
            gbar_ece, h_par_mean, ...
            j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_s1, n_s2, ...
            Q_reg, Q_reg_base, K_whanau, Jr, dt));
        check(max(abs(th_vec(:) - th_gpu(:))) < 1e-12, ...
            sprintf('aprimeFn CPU vs GPU mismatch at agej=%d', agej));
    end
end

% -------------------------------------------------------------------------
% PART B: ReturnFn_SpatialHH (5D) & ReturnFn_SpatialHH_Compact4D (4D)
% -------------------------------------------------------------------------
w_reg = 1.10; r = 0.04; G_reg = 0.08; phi_nd = 0.45; mu_maint = 0.02;
upsilon_h = 0.12; chi_bar = 0.80; ebar_energy = 0.03;
Transfer_Geo = 0.01; p_super = 0.22; c_floor = 0.05; s_sub = 0.15;
omega_ic = 0.35; delta_hc = 0.05; alpha_I = 0.50; alpha_H = 0.35;
b1_beq = 1.50; b2_beq = 2.00; YouthGrant = 0.0;
tau_l = 0.22; tau_c = 0.15; tau_k = 0.28; tau_a = 0.0; tau_b = 0.0;
sj = 0.985;

% Orthogonal dimensions: aprime [4 x 1 x 1], a [1 x 3 x 1], z [1 x 1 x 2]
ap_col = [0.0; 0.5; 1.5; 3.5];             % [4 x 1 x 1]
a_row  = [0.2, 1.5, 4.0];                  % [1 x 3 x 1]
z_page = reshape([0.85, 1.20], 1, 1, 2);   % [1 x 1 x 2]
[AP, A, Z] = ndgrid(ap_col(:), a_row(:), z_page(:));

l_val = 0.65; Ih_val = 0.05; ic_val = 0.0203; h_val = 1.00; hprime_val = 1.00; th_val = 1.00;

% Stage 1 Parenting (agej = 2): ic > 0 is valid
F5_vec = ReturnFn_SpatialHH(l_val, Ih_val, ic_val, ap_col, hprime_val, a_row, h_val, th_val, z_page, ...
    w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
    Transfer_Geo, p_super, c_floor, G_ece1, G_ece2, gbar_ece, s_sub, ...
    omega_ic, gamma1_self, gamma1_inv, gamma1_par, phi1_ces, ...
    gamma2_self, gamma2_inv, gamma2_par, phi2_ces, ...
    delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
    tau_l, tau_c, tau_k, tau_a, tau_b, 2, Jr, sj, dt, ...
    j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_s1, n_s2, ...
    Q_reg_base, K_whanau);

F5_sca = arrayfun(@(ap, a, z) ReturnFn_SpatialHH( ...
    l_val, Ih_val, ic_val, ap, hprime_val, a, h_val, th_val, z, ...
    w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
    Transfer_Geo, p_super, c_floor, G_ece1, G_ece2, gbar_ece, s_sub, ...
    omega_ic, gamma1_self, gamma1_inv, gamma1_par, phi1_ces, ...
    gamma2_self, gamma2_inv, gamma2_par, phi2_ces, ...
    delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
    tau_l, tau_c, tau_k, tau_a, tau_b, 2, Jr, sj, dt, ...
    j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_s1, n_s2, ...
    Q_reg_base, K_whanau), AP, A, Z);

check(isequal(size(F5_vec), [4, 3, 2]), 'ReturnFn_SpatialHH 3D broadcast shape mismatch');
check(isequal(isinf(F5_vec), isinf(F5_sca)), 'ReturnFn_SpatialHH feasibility mask mismatch');
fin5 = isfinite(F5_vec);
check(any(fin5(:)), 'ReturnFn_SpatialHH produced zero finite values on valid parenting state');
check(max(abs(F5_vec(fin5) - F5_sca(fin5))) < 1e-12, 'ReturnFn_SpatialHH scalar vs vec mismatch');

% Non-parenting age (agej = 1) with ic > 0 must be strictly infeasible (-Inf)
F5_invalid_ic = ReturnFn_SpatialHH(l_val, Ih_val, ic_val, ap_col, hprime_val, a_row, h_val, th_val, z_page, ...
    w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
    Transfer_Geo, p_super, c_floor, G_ece1, G_ece2, gbar_ece, s_sub, ...
    omega_ic, gamma1_self, gamma1_inv, gamma1_par, phi1_ces, ...
    gamma2_self, gamma2_inv, gamma2_par, phi2_ces, ...
    delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
    tau_l, tau_c, tau_k, tau_a, tau_b, 1, Jr, sj, dt, ...
    j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_s1, n_s2, ...
    Q_reg_base, K_whanau);
check(all(F5_invalid_ic(:) == -Inf), 'Expected -Inf for ic > 0 outside parenting ages');

% Compact 4D check (agej = 3 parenting, fractional statutory Jr = 10.4 -> super_age = 67)
Jr_frac = 1 + (67.0 - 20.0) / dt;
F4_vec = ReturnFn_SpatialHH_Compact4D(l_val, Ih_val, ic_val, ap_col, hprime_val, a_row, h_val, z_page, ...
    w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
    Transfer_Geo, p_super, c_floor, G_ece1, gbar_ece, K_whanau, omega_ic, ...
    delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
    tau_l, tau_c, tau_k, tau_a, tau_b, 3, Jr_frac, sj, dt, ...
    j_s1_start, j_s2_end);
F4_sca = arrayfun(@(ap, a, z) ReturnFn_SpatialHH_Compact4D( ...
    l_val, Ih_val, ic_val, ap, hprime_val, a, h_val, z, ...
    w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
    Transfer_Geo, p_super, c_floor, G_ece1, gbar_ece, K_whanau, omega_ic, ...
    delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
    tau_l, tau_c, tau_k, tau_a, tau_b, 3, Jr_frac, sj, dt, ...
    j_s1_start, j_s2_end), AP, A, Z);

fin4 = isfinite(F4_vec);
check(any(fin4(:)) && isequal(isinf(F4_vec), isinf(F4_sca)), ...
    'ReturnFn_SpatialHH_Compact4D feasibility check failed');
check(max(abs(F4_vec(fin4) - F4_sca(fin4))) < 1e-12, ...
    'ReturnFn_SpatialHH_Compact4D scalar vs vec mismatch');

if hasGpu
    F5_gpu = gather(arrayfun(@ReturnFn_SpatialHH, ...
        l_val, Ih_val, ic_val, gpuArray(AP), hprime_val, gpuArray(A), h_val, th_val, gpuArray(Z), ...
        w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
        Transfer_Geo, p_super, c_floor, G_ece1, G_ece2, gbar_ece, s_sub, ...
        omega_ic, gamma1_self, gamma1_inv, gamma1_par, phi1_ces, ...
        gamma2_self, gamma2_inv, gamma2_par, phi2_ces, ...
        delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
        tau_l, tau_c, tau_k, tau_a, tau_b, 2, Jr, sj, dt, ...
        j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_s1, n_s2, ...
        Q_reg_base, K_whanau));
    F4_gpu = gather(arrayfun(@ReturnFn_SpatialHH_Compact4D, ...
        l_val, Ih_val, ic_val, gpuArray(AP), hprime_val, gpuArray(A), h_val, gpuArray(Z), ...
        w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
        Transfer_Geo, p_super, c_floor, G_ece1, gbar_ece, K_whanau, omega_ic, ...
        delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
        tau_l, tau_c, tau_k, tau_a, tau_b, 3, Jr_frac, sj, dt, ...
        j_s1_start, j_s2_end));
    check(max(abs(F5_vec(fin5) - F5_gpu(fin5))) < 1e-12, 'ReturnFn_SpatialHH GPU parity mismatch');
    check(max(abs(F4_vec(fin4) - F4_gpu(fin4))) < 1e-12, 'ReturnFn_SpatialHH_Compact4D GPU parity mismatch');
end
end

function check(cond, msg)
if ~cond
    error('tests:fail', '%s', msg);
end


end
